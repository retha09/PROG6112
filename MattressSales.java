    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
if (txtDisplay.getText().trim().isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(this, "Nothing to save yet.");
    return;
}

try (java.io.PrintWriter writer = new java.io.PrintWriter(new java.io.FileWriter("SalesReport.txt"))) {
    writer.println("=== MATTRESS SALES REPORT ===");
    writer.print(txtDisplay.getText());
    javax.swing.JOptionPane.showMessageDialog(this, "Saved to SalesReport.txt!");
} catch (java.io.IOException ex) {
    javax.swing.JOptionPane.showMessageDialog(this, "Error saving file: " + ex.getMessage());
}
        // TODO add your handling code here:
    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnProccessActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnProccessActionPerformed
String customerName = txtCustomerName.getText().trim();
String productName = cmbProductName.getSelectedItem().toString();
String priceInput = txtProductPrice.getText().trim();

if (customerName.isEmpty() || priceInput.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(this, "Please enter the customer name and product price.");
    return;
}

try {
    double price = Double.parseDouble(priceInput);
    double vat = price * 0.15;
    double commission = price * 0.05;
    double totalSale = price + vat + commission;

    String output = "Customer Name : " + customerName + "\n"
                  + "Product Name  : " + productName + "\n"
                  + String.format("Product Price : R %.2f\n", price)
                  + String.format("VAT (15%%)     : R %.2f\n", vat)
                  + String.format("Commission(5%%): R %.2f\n", commission)
                  + String.format("Total Sale    : R %.2f\n", totalSale)
                  + "----------------------------------------\n";

    txtDisplay.append(output);

} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(this, "Please enter a valid number for the product price.");
}
        // TODO add your handling code here:
    }//GEN-LAST:event_btnProccessActionPerformed

